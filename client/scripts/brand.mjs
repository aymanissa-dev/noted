// Regenerates every logo asset from the traced SVGs in client/brand/ (themselves traced from
// noted-logo-source.png, the original artwork). Run: node client/scripts/brand.mjs
// Writes: src/brand.js (paths for <Logo>), public/favicon.svg (light/dark), public/favicon.ico
// (16/32/48), favicon.png, apple-touch-icon.png, pwa-192x192.png, pwa-512x512.png,
// maskable-512x512.png, og.png (1200×630) and public/brand/noted-logo*.svg / noted-mark.svg.
import puppeteer from '../../node_modules/puppeteer-core/lib/esm/puppeteer/puppeteer-core.js';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (f) => readFileSync(root + f, 'utf8');
const pick = (svg, attr) => svg.match(new RegExp(` ${attr}="([^"]+)"`))[1];
const logo = read('brand/noted-logo.svg'); const mark = read('brand/noted-mark.svg');
const L = { viewBox: pick(logo, 'viewBox'), d: pick(logo, 'd') };
const M = { viewBox: pick(mark, 'viewBox'), d: pick(mark, 'd') };
const INK = '#111418'; const PAPER = '#ffffff';

writeFileSync(root + 'src/brand.js', `// Generated by client/scripts/brand.mjs from client/brand/*.svg (traced from noted-logo-source.png).
// The Noted logo: the "N" mark (a page with a folded corner) and the full wordmark, drawn in currentColor.
export const LOGO = { viewBox: '${L.viewBox}', d: '${L.d}' };
export const MARK = { viewBox: '${M.viewBox}', d: '${M.d}' };
`);

// stroke: thickens the outline for tiny sizes (the mark is a thin line drawing).
const svg = (g, { fill = 'currentColor', stroke = 0, extra = '' } = {}) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${g.viewBox}"${extra}><path fill="${fill}" fill-rule="evenodd"${stroke ? ` stroke="${fill}" stroke-width="${stroke}" stroke-linejoin="round"` : ''} d="${g.d}"/></svg>`;

mkdirSync(root + 'public/brand', { recursive: true });
writeFileSync(root + 'public/brand/noted-logo.svg', svg(L, { fill: INK }));
writeFileSync(root + 'public/brand/noted-logo-white.svg', svg(L, { fill: PAPER }));
writeFileSync(root + 'public/brand/noted-mark.svg', svg(M, { fill: INK }));
// Browser tab icon: black mark on a white tile (readable on light and dark tab strips); in dark
// mode the tile turns dark and the mark white.
const [, , mw, mh] = M.viewBox.split(' ').map(Number);
const S = Math.max(mw, mh) * 1.28; const ox = (S - mw) / 2; const oy = (S - mh) / 2;
writeFileSync(root + 'public/favicon.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S.toFixed(0)} ${S.toFixed(0)}"><style>.t{fill:${PAPER}}.m{fill:${INK};stroke:${INK}}@media (prefers-color-scheme:dark){.t{fill:#1c1917}.m{fill:#fafaf9;stroke:#fafaf9}}</style><rect class="t" width="${S.toFixed(0)}" height="${S.toFixed(0)}" rx="${(S * 0.22).toFixed(0)}"/><path class="m" transform="translate(${ox.toFixed(1)} ${oy.toFixed(1)})" fill-rule="evenodd" stroke-width="6" stroke-linejoin="round" d="${M.d}"/></svg>`);

const b = await puppeteer.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
const p = await b.newPage();
const font = `data:font/woff2;base64,${readFileSync(root + 'node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2').toString('base64')}`;
const shot = async (w, h, body, out) => {
  await p.setViewport({ width: w, height: h, deviceScaleFactor: 1 });
  await p.setContent(`<!doctype html><style>@font-face{font-family:G;src:url(${font})}html,body{margin:0;width:${w}px;height:${h}px;overflow:hidden;background:transparent}svg{display:block}</style>${body}`, { waitUntil: 'load' });
  await p.evaluate(() => document.fonts.ready);
  return p.screenshot({ type: 'png', omitBackground: true, ...(out && { path: root + out }) });
};
// App icon: mark centred on a tile. `scale` = mark height / tile; `round` = corner radius share.
const tile = (size, { scale, round = 0.22, stroke = 0 }) => {
  const h = size * scale;
  return `<div style="width:${size}px;height:${size}px;background:${PAPER};border-radius:${size * round}px;display:grid;place-items:center">${svg(M, { fill: INK, stroke, extra: ` style="height:${h}px;width:auto"` })}</div>`;
};
await shot(180, 180, tile(180, { scale: 0.6, round: 0 }), 'public/apple-touch-icon.png'); // iOS rounds it
await shot(192, 192, tile(192, { scale: 0.58 }), 'public/pwa-192x192.png');
await shot(512, 512, tile(512, { scale: 0.58 }), 'public/pwa-512x512.png');
await shot(512, 512, tile(512, { scale: 0.5, round: 0 }), 'public/maskable-512x512.png'); // inside the 80% safe zone
await shot(64, 64, tile(64, { scale: 0.66, stroke: 6 }), 'public/favicon.png');
const icos = [];
for (const s of [16, 32, 48]) icos.push([s, await shot(s, s, tile(s, { scale: s === 16 ? 0.78 : 0.7, round: 0.18, stroke: s === 16 ? 14 : 8 }))]);
// ICO with PNG entries.
const head = Buffer.alloc(6 + 16 * icos.length); head.writeUInt16LE(1, 2); head.writeUInt16LE(icos.length, 4);
let off = head.length;
icos.forEach(([s, png], i) => {
  const e = 6 + 16 * i; head[e] = s; head[e + 1] = s; head.writeUInt16LE(1, e + 4); head.writeUInt16LE(32, e + 6);
  head.writeUInt32LE(png.length, e + 8); head.writeUInt32LE(off, e + 12); off += png.length;
});
writeFileSync(root + 'public/favicon.ico', Buffer.concat([head, ...icos.map(([, png]) => png)]));

// Social card.
await shot(1200, 630, `<div style="width:1200px;height:630px;box-sizing:border-box;padding:0 96px;display:flex;flex-direction:column;justify-content:center;align-items:flex-start;gap:40px;font-family:G,sans-serif;color:${INK};
  background:${PAPER};background-image:linear-gradient(rgba(17,20,24,.045) 1px,transparent 1px),linear-gradient(90deg,rgba(17,20,24,.045) 1px,transparent 1px);background-size:48px 48px;background-position:-1px -1px">
  ${svg(L, { fill: INK, extra: ' style="height:112px;width:auto;margin-bottom:12px"' })}
  <div style="font-size:76px;font-weight:650;letter-spacing:-0.035em;line-height:1.05">Write it down. Find it later.</div>
  <div style="font-size:28px;color:#57534e;letter-spacing:-0.01em">Private notes that work offline. No tracking, no AI.</div>
</div>`, 'public/og.png');
await b.close();
console.log('brand assets written');
